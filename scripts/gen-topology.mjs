// Regenerates src/core/topology.ts from the MediaPipe package so the main
// bundle does not need to import the whole vision bundle for a few arrays.
// Usage: node scripts/gen-topology.mjs
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

globalThis.self = globalThis;
const { FaceLandmarker: F } = await import('@mediapipe/tasks-vision');
const flat = (c) => c.flatMap((e) => [e.start, e.end]);
const sets = {
  TESSELATION: F.FACE_LANDMARKS_TESSELATION,
  FACE_OVAL: F.FACE_LANDMARKS_FACE_OVAL,
  LIPS: F.FACE_LANDMARKS_LIPS,
  LEFT_EYE: F.FACE_LANDMARKS_LEFT_EYE,
  RIGHT_EYE: F.FACE_LANDMARKS_RIGHT_EYE,
  LEFT_EYEBROW: F.FACE_LANDMARKS_LEFT_EYEBROW,
  RIGHT_EYEBROW: F.FACE_LANDMARKS_RIGHT_EYEBROW,
  LEFT_IRIS: F.FACE_LANDMARKS_LEFT_IRIS,
  RIGHT_IRIS: F.FACE_LANDMARKS_RIGHT_IRIS,
};
let out = '// AUTO-GENERATED by scripts/gen-topology.mjs from @mediapipe/tasks-vision (Apache-2.0).\n';
out += '// Each array is a flat list of edges: [a0, b0, a1, b1, ...] of landmark indices.\n\n';
for (const [name, conns] of Object.entries(sets)) {
  out += `export const ${name}_EDGES = new Uint16Array([${flat(conns).join(',')}]);\n`;
}
const root = join(dirname(fileURLToPath(import.meta.url)), '..');
writeFileSync(join(root, 'src/core/topology.ts'), out);
console.log('wrote src/core/topology.ts');
